# Generates source/host/modpack_data.c: the pixel differences between assets/original (the graphics dump) and
# assets/mod (the example pack). Needs Python 3 with Pillow and numpy; it is only run by hand when the pack changes.
#   python make_modpack.py <folder with original/ and mod/> <output modpack_data.c>
# The format is described at the top of source/host/modpack.c.
import os, sys, zlib, struct
import numpy as np
from PIL import Image
ROOT = sys.argv[1]          # build/assets
OUT = sys.argv[2]           # modpack_data.c
def varint(n):
    b = bytearray()
    while True:
        c = n & 0x7F; n >>= 7
        if n: b.append(c | 0x80)
        else: b.append(c); return bytes(b)
entries = []
for dp, _, fs in os.walk(os.path.join(ROOT, 'original')):
    for f in sorted(fs):
        if not f.endswith('.png'): continue
        po = os.path.join(dp, f)
        rel = os.path.relpath(po, os.path.join(ROOT, 'original')).replace(chr(92), '/')
        pm = os.path.join(ROOT, 'mod', rel)
        a = Image.open(po); b = Image.open(pm)
        indexed = a.mode == 'P'
        if indexed:
            assert b.mode == 'P' and a.getpalette() == b.getpalette()
            A = np.array(a)[:, :, None]; B = np.array(b)[:, :, None]
        else:
            A = np.array(a.convert('RGBA')); B = np.array(b.convert('RGBA'))
        assert A.shape == B.shape, rel
        ch = (A != B).any(axis=2)
        if not ch.any(): continue
        h, w = ch.shape
        flat = ch.reshape(-1)
        # runs: unchanged, changed, unchanged, ...
        idx = np.flatnonzero(np.diff(flat.astype(np.int8))) + 1
        bounds = np.concatenate(([0], idx, [flat.size]))
        runs = np.diff(bounds)
        if flat[0]: runs = np.concatenate(([0], runs))
        runbytes = b''.join(varint(int(r)) for r in runs)
        vals = B.reshape(-1, B.shape[2])[flat]
        planes = b''.join(vals[:, c].tobytes() for c in range(vals.shape[1]))
        crc = zlib.crc32(B.astype(np.uint8).tobytes()) & 0xFFFFFFFF
        name = rel.encode()
        e = bytes([len(name)]) + name + bytes([1 if indexed else 4]) + struct.pack('<HHI', w, h, crc) + struct.pack('<II', len(runs), len(vals)) + runbytes + planes
        entries.append((rel, int(ch.sum()), e))
raw = struct.pack('<I', len(entries)) + b''.join(e for _, _, e in entries)
co = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
comp = co.compress(raw) + co.flush()
for r, n, e in entries: print('%-30s %7d px  %8d bytes' % (r, n, len(e)))
print('raw', len(raw), 'deflated', len(comp))
lines = []
for i in range(0, len(comp), 24):
    lines.append('    ' + ', '.join('0x%02X' % x for x in comp[i:i + 24]) + ',')
src = '''/*
 * modpack_data.c - The differences between the dump of the game's graphics (assets/original) and the example graphics
 * pack (assets/mod). GENERATED by source/tools/make_modpack.py; see modpack.c for how it is used and the format.
 *
 * Only the pixels that the pack CHANGES are stored (their values and the positions as run lengths). Nothing of the
 * pixels that are the game's own is in here: the pack is rebuilt on the first run, from the player's own dump.
 */
#include <stddef.h>
#include <stdint.h>

const size_t modpack_raw_size = %d;
const size_t modpack_size = %d;
const uint8_t modpack_data[%d] = {
%s
};
''' % (len(raw), len(comp), len(comp), '\n'.join(lines))
open(OUT, 'w', newline='\r\n' if False else '\n').write(src)
